#@title Normalization via standardization (features have a mean of 0 and a standard deviation of 1)

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

rest_data = csv_file.drop(['loan_status'], axis = 1)
target = csv_file['loan_status']
x_train, x_test, y_train, y_test = train_test_split(rest_data, target, test_size = 0.2, random_state = 67) # 80% training, 20% testing
scaler = StandardScaler()
x_train_scaled = scaler.fit_transform(x_train)
x_test_scaled = scaler.transform(x_test)

#@title Supervised models

from sklearn.linear_model import LogisticRegression
from sklearn.neighbors import KNeighborsClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import roc_curve, auc

models = {
    'Logistic Regression': LogisticRegression(),
    'KNN': KNeighborsClassifier(),
    'Neural Network': MLPClassifier(hidden_layer_sizes = (8, 8, 8), activation = 'relu', solver = 'adam', max_iter = 1000, random_state = 67)
}

plt.figure(figsize = (10, 10))
dictn = {}

for name, model in models.items():
  model.fit(x_train_scaled, y_train)
  y_pred = model.predict(x_test_scaled)
  y_prob = model.predict_proba(x_test_scaled)[:, 1]

  fpr, tpr, x = roc_curve(y_test, y_prob)
  roc_auc = auc(fpr, tpr)
  dictn[name] = roc_auc

  plt.plot(fpr, tpr, label = f'{name} (AUC = {roc_auc:.2f})')

plt.plot([0, 1], [0, 1], 'k--', label = 'Random Guess')
plt.xlabel('<--- False Positive Rate --->')
plt.ylabel('<--- True Positive Rate --->')
plt.title('ROC Curve Comparison - Loan Approval Dataset')
plt.legend(loc = 'lower right')
plt.grid()
plt.show()

#@title Barchart of Roc Auc score

import matplotlib.pyplot as plt
import pandas as pd

roc_auc_scores = pd.Series(dictn, name = 'ROC AUC')

plt.figure(figsize = (6, 4))
roc_auc_scores.plot(kind = 'bar', color = ['red', 'green', 'blue'])
plt.title('Model Accuracy')
plt.xlabel('Model Name')
plt.ylabel('<--- ROC AUC Score --->')
plt.xticks(rotation = 0)
plt.grid(axis = 'y', linestyle = '--', alpha = 1)
plt.tight_layout()
plt.show()

#@title Neural network confusion matrix, precission, recall, f1 score

from sklearn.metrics import confusion_matrix, ConfusionMatrixDisplay, accuracy_score
from sklearn.metrics import classification_report

mlp = models['Neural Network'] # reuse the model already fitted above
y_pred = mlp.predict(x_test_scaled)
matrix = confusion_matrix(y_test, y_pred)
display = ConfusionMatrixDisplay(confusion_matrix = matrix)
display.plot(cmap = 'Blues')
plt.title('Neural Network Confusion Matrix')
plt.show()

print('\nNeural Network:', accuracy_score(y_test, y_pred))
print('-------------------------------------------------------------------')
print(classification_report(y_test, y_pred, target_names = ['Rejected (0)', 'Approved (1)']))

