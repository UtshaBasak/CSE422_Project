#@title Checking null values

import pandas as pd
from pathlib import Path

# Dataset lives at <repo>/data/, resolved relative to this file so the script
# can be run from any working directory.
DATA_PATH = Path(__file__).resolve().parents[1] / 'data' / 'Loan Approval Dataset.csv'

csv_file = pd.read_csv(DATA_PATH)
csv_file = csv_file.dropna() # no null values in any column
csv_file.info()

#@title Types of objects in a column

print(csv_file['person_gender'].value_counts())
print(csv_file['person_education'].value_counts())
print(csv_file['person_home_ownership'].value_counts())
print(csv_file['loan_intent'].value_counts())
print(csv_file['previous_loan_defaults_on_file'].value_counts())

#@title Assigning object values to categorical values

from sklearn.preprocessing import LabelEncoder
encode = LabelEncoder()

csv_file['person_gender'] = csv_file['person_gender'].map({'male': 0, 'female': 1})
csv_file['person_education'] = csv_file['person_education'].map({'Bachelor': 0, 'Associate': 1, 'High School': 2, 'Master': 3, 'Doctorate': 4})
csv_file['person_home_ownership'] = csv_file['person_home_ownership'].map({'RENT': 0, 'MORTGAGE': 1, 'OWN': 2, 'OTHER': 3})
csv_file['loan_intent'] = csv_file['loan_intent'].map({'EDUCATION': 0, 'MEDICAL': 1, 'VENTURE': 2, 'PERSONAL': 3, 'DEBTCONSOLIDATION': 4, 'HOMEIMPROVEMENT': 5,})
csv_file['previous_loan_defaults_on_file'] = csv_file['previous_loan_defaults_on_file'].map({'Yes': 0, 'No': 1})

csv_file

#@title Correlation (only works with numerical data)

import seaborn as sns
import matplotlib.pyplot as plt
correlation = csv_file.corr() # no non-numerical value to remove
correlation

#@title Heatmap
sns.heatmap(correlation, cmap = 'YlGnBu')

#@title Checking imbalance output feature
csv_file['loan_status'].value_counts().sort_index()

#@title Output barchart

import matplotlib.pyplot as plt
bar_chart = csv_file['loan_status'].value_counts()

# Plot
plt.figure(figsize = (6, 4))
bar_chart.plot(kind = 'bar', color = ['red', 'green'])
